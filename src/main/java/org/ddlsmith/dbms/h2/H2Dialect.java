    /* ------------------------------------------------------------------ rendering differences */

    /**
     * H2 2.x spells identity columns {@code GENERATED BY DEFAULT AS IDENTITY} and rejects a
     * {@code DEFAULT} clause on the same column, so the default is suppressed for identity columns.
     * H2 also makes identity columns implicitly {@code NOT NULL}; an explicit {@code NOT NULL} is
     * still emitted when the column asks for it.
     */
    @Override
    protected String renderColumnDefinition(Column column) {
        if (!column.isIdentity()) {
            return super.renderColumnDefinition(column);
        }
        StringBuilder sb = new StringBuilder();
        sb.append(quote(column.getName())).append(' ').append(renderType(column.getType()));
        sb.append(" GENERATED BY DEFAULT AS IDENTITY");
        if (!column.isNullable()) {
            sb.append(" NOT NULL");
        }
        if (column.isUnique() && getFeatures().supports(DDLFeature.INLINE_UNIQUE)) {
            sb.append(" UNIQUE");
        }
        if (column.getCheckExpression() != null && getFeatures().supports(DDLFeature.INLINE_CHECK)) {
            sb.append(" CHECK (").append(column.getCheckExpression()).append(')');
        }
        return sb.toString();
    }

    @Override
    public String renderAlterAction(org.ddlsmith.ddl.alter.AlterTableAction action) {
        return action.accept(h2AlterActionRenderer);
    }

    /**
     * H2 has no {@code CASCADE} on {@code DROP SEQUENCE} (it is a syntax error), although
     * {@code DROP TABLE … CASCADE}, {@code DROP VIEW … CASCADE} and {@code DROP SCHEMA … CASCADE}
     * are fine. The generic {@code CASCADE_DROP} feature therefore has to be suppressed here.
     */
    @Override
    public String visit(DropSequence statement) {
        StringBuilder sb = new StringBuilder("DROP SEQUENCE ");
        if (statement.isIfExists() && getFeatures().supports(DDLFeature.DROP_IF_EXISTS)) {
            sb.append("IF EXISTS ");
        }
        sb.append(renderTableReference(statement.getSchemaName(), statement.getSequenceName()));
        return sb.toString();
    }

    /**
     * H2 expresses table and column comments as separate {@code COMMENT ON} statements, so a
     * {@code CREATE TABLE} expands into the table plus one statement per comment. Single quotes are
     * escaped by doubling them.
     */
    @Override
    public List<String> renderAll(DDLStatement statement) {
        if (!(statement instanceof CreateTable)) {
            return super.renderAll(statement);
        }
        List<String> statements = new ArrayList<>();
        statements.add(render(statement));
        Table table = ((CreateTable) statement).getTable();
        String qualifiedName = renderTableName(table);
        if (table.getComment() != null) {
            statements.add("COMMENT ON TABLE " + qualifiedName + " IS " + renderStringLiteral(table.getComment()));
        }
        for (Column column : table.getColumns()) {
            if (column.getComment() != null) {
                statements.add("COMMENT ON COLUMN " + qualifiedName + "." + quote(column.getName()) + " IS "
                        + renderStringLiteral(column.getComment()));
            }
        }
        return statements;
    }

    /**
     * H2 literals: {@code TRUE}/{@code FALSE} for booleans, typed ISO literals for date and time
     * values, {@code X'..'} for binary data and ordinary quoted strings for everything else. All
     * spellings below were verified against H2 2.3.232.
     */
    @Override
    public String renderLiteral(Object value, DataType type) {
        if (value == null) {
            return "NULL";
        }
        if (value instanceof byte[]) {
            return renderBinaryLiteral((byte[]) value);
        }
        if (type != null) {
            switch (type.getCategory()) {
            case BOOLEAN:
                return renderBooleanLiteral(value);
            case DATE:
                return "DATE " + renderStringLiteral(value);
            case TIME:
                return "TIME " + renderStringLiteral(value);
            case TIMESTAMP:
                return "TIMESTAMP " + renderStringLiteral(value);
            case TIMESTAMPTZ:
                return "TIMESTAMP WITH TIME ZONE " + renderStringLiteral(value);
            case BLOB:
                if (value instanceof String) {
                    return renderStringLiteral(value);
                }
                break;
            case JSON:
                return "JSON " + renderStringLiteral(value);
            default:
                break;
            }
        }
        if (value instanceof Boolean) {
            return renderBooleanLiteral(value);
        }
        if (value instanceof Number) {
            return value.toString();
        }
        return renderStringLiteral(value);
    }

    private static String renderBooleanLiteral(Object value) {
        if (value instanceof Boolean) {
            return ((Boolean) value) ? "TRUE" : "FALSE";
        }
        if (value instanceof Number) {
            return ((Number) value).intValue() != 0 ? "TRUE" : "FALSE";
        }
        String text = value.toString().trim();
        if (text.equalsIgnoreCase("true") || text.equalsIgnoreCase("t") || text.equalsIgnoreCase("yes")
                || text.equals("1")) {
            return "TRUE";
        }
        if (text.equalsIgnoreCase("false") || text.equalsIgnoreCase("f") || text.equalsIgnoreCase("no")
                || text.equals("0")) {
            return "FALSE";
        }
        return renderStringLiteral(value);
    }

    private static String renderBinaryLiteral(byte[] bytes) {
        StringBuilder sb = new StringBuilder("X'");
        for (byte b : bytes) {
            sb.append(String.format("%02X", b));
        }
        return sb.append('\'').toString();
    }

    private static String renderStringLiteral(Object value) {
        return "'" + value.toString().replace("'", "''") + "'";
    }

    /** The H2 specific {@code ALTER TABLE} actions. */
    protected class H2AlterActionRenderer extends AlterActionRenderer {

        /** H2 spells a type change {@code ALTER COLUMN c SET DATA TYPE t}. */
        @Override
        public String visit(AlterColumnType action) {
            StringBuilder sb = new StringBuilder("ALTER COLUMN ").append(quote(action.getColumnName()));
            sb.append(" SET DATA TYPE ").append(renderType(action.getNewType()));
            if (action.getUsingExpression() != null
                    && getFeatures().supports(DDLFeature.ALTER_COLUMN_TYPE_USING)) {
                sb.append(" USING ").append(action.getUsingExpression());
            }
            return sb.toString();
        }

        /**
         * {@code ADD [CONSTRAINT name] PRIMARY KEY (…)}.
         *
         * <p>The generic rendering is already correct for H2; spelling the primary key out keeps it
         * named even if {@code NAMED_PRIMARY_KEY} were ever dropped, because an unnamed H2 primary
         * key is auto-named {@code CONSTRAINT_<hash>} and can then no longer be dropped by name.
         * Every other constraint kind (including a named foreign key, which used to need a workaround
         * for a double {@code CONSTRAINT} prefix in {@code renderConstraintDefinition}) delegates to
         * the standard rendering, so H2 stays on the same code path as the other dialects.</p>
         */
        @Override
        public String visit(AddConstraint action) {
            ConstraintDefinition definition = action.getDefinition();
            if (definition.getKind() != ConstraintDefinition.Kind.PRIMARY_KEY) {
                return super.visit(action);
            }
            StringBuilder sb = new StringBuilder("ADD ");
            if (definition.getName() != null) {
                sb.append("CONSTRAINT ").append(quote(definition.getName())).append(' ');
            }
            sb.append("PRIMARY KEY (").append(joinQuoted(definition.getPrimaryKey().getColumns())).append(')');
            return sb.toString();
        }
    }
