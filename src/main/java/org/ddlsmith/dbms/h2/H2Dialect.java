    /**
     * @return every {@link DDLFeature} constant that is neither declared in {@link #FEATURES} nor
     *         explained in {@link #UNSUPPORTED}. An empty list means every constant was decided
     *         explicitly; {@code SelfCheck} fails when it is not empty.
     */
    public static List<DDLFeature> unclassifiedFeatures() {
        List<DDLFeature> result = new ArrayList<>();
        for (DDLFeature feature : DDLFeature.values()) {
            if (FEATURES.supports(feature) == UNSUPPORTED.containsKey(feature)) {
                result.add(feature);
            }
        }
        return result;
    }

